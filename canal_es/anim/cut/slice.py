"""Slice an AI 'puppet parts sheet' (transparent PNG) into the parts cutout.js expects and measure their joints.
usage: python slice.py SHEET.png NAME            -> anim/cut/NAME/{head,torso,upper,fore,hand,fist,leg,shoe}.png + spec.json
       python slice.py --specs                   -> rebuild anim/cut/specs.js from every NAME/spec.json
The sheet must hold 8 separate parts (head with blank face, torso, upper arm, forearm, open hand, fist, leg, shoe).
Classification: head = biggest part with both skin and hair; hands = the two compact skin-only parts
(open hand = the wider one, it has a thumb); torso = biggest of the rest; leg = longest tube;
upper/forearm = the other two tubes in sheet order (left/top first); shoe = what remains."""
import glob, json, os, sys
import numpy as np
from PIL import Image
from scipy import ndimage

HERE = os.path.dirname(os.path.abspath(__file__))

def write_specs():
    specs = {}
    for f in sorted(glob.glob(os.path.join(HERE, '*', 'spec.json'))):
        specs[os.path.basename(os.path.dirname(f))] = json.load(open(f))
    open(os.path.join(HERE, 'specs.js'), 'w').write('/* generated by slice.py --specs: joint metrics of each cut-out part, in image pixels */\nconst CUT_SPEC = ' + json.dumps(specs, indent=1) + ';\n')
    print('specs.js:', ', '.join(specs))

def skin_mask(A):
    r, g, b, a = (A[..., i].astype(int) for i in range(4))
    return (a > 200) & (r > 195) & (g > 180) & (b > 195) & (abs(r - b) < 40)

def row_span(m, y):
    xs = np.where(m[y])[0]
    return (xs.min(), xs.max()) if len(xs) else None

def tube_metrics(m):
    H, W = m.shape
    spans = [row_span(m, int(H * f)) for f in (.3, .4, .5, .6, .7)]
    spans = [s for s in spans if s]
    cx = float(np.mean([(a + b) / 2 for a, b in spans])); w = float(np.median([b - a for a, b in spans]))
    return cx, w

def main(sheet, name):
    A = np.array(Image.open(sheet).convert('RGBA'))
    a = A[..., 3].astype(float)
    # parts sometimes touch through faint glow: raise the alpha threshold / erode until 8 parts separate
    for thr, ero in ((40, 0), (128, 0), (200, 0), (200, 3), (200, 6)):
        m0 = a > thr
        if ero: m0 = ndimage.binary_erosion(m0, iterations=ero)
        lab, n = ndimage.label(m0)
        sizes = ndimage.sum(np.ones_like(a), lab, range(1, n + 1))
        if (sizes >= 1500).sum() >= 8: break
    if ero:   # grow the eroded labels back over the full alpha
        lab = ndimage.grey_dilation(lab, size=(2 * ero + 3, 2 * ero + 3)) * (a > 40)
    comps = []
    for i in np.argsort(-sizes)[:8]:
        if sizes[i] < 1500: continue
        # keep the solid part only: some sheets paint a soft white glow around each part, which would leave gaps at the joints
        mm = ndimage.binary_dilation((lab == i + 1) & (a > 128), iterations=2)
        ys, xs = np.where(mm); y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
        crop = A[y0:y1, x0:x1].copy(); crop[..., 3] = np.where(mm[y0:y1, x0:x1], crop[..., 3], 0)
        crop[..., 3] = (np.clip((crop[..., 3].astype(float) - 110) / 110, 0, 1) * 255).astype(np.uint8)
        m = crop[..., 3] > 128; sk = skin_mask(crop)
        comps.append(dict(img=crop, m=m, area=int(m.sum()), skin=float(sk.sum() / max(1, m.sum())), w=x1 - x0, h=y1 - y0, x=x0, y=y0))
    if len(comps) != 8: sys.exit(f'expected 8 parts, found {len(comps)}')
    parts = {}
    rest = list(comps)
    def take(c):
        rest[:] = [x for x in rest if x is not c]; return c
    # hands: compact, mostly skin
    hands = sorted([c for c in rest if c['skin'] > .6 and .7 < c['w'] / c['h'] < 1.5], key=lambda c: c['area'])[:2]
    if len(hands) < 2: sys.exit('could not find two hands')
    for c in hands: take(c)
    hands.sort(key=lambda c: c['w'] / c['h'])
    parts['fist'], parts['hand'] = hands
    # head: has skin but is not a hand, biggest such
    heads = sorted([c for c in rest if c['skin'] > .15], key=lambda c: -c['area'])
    parts['head'] = take(heads[0])
    parts['torso'] = take(max(rest, key=lambda c: c['area']))
    tubes = sorted([c for c in rest if c['h'] / c['w'] > 1.6], key=lambda c: -c['h'])
    if len(tubes) < 3: sys.exit('could not find leg + two arm tubes')
    leg = max(tubes, key=lambda c: c['h'] * (c['h'] / c['w'])); parts['leg'] = take(leg)
    arms = sorted([c for c in rest if c['h'] / c['w'] > 1.6], key=lambda c: (c['y'] // 300, c['x']))[:2]
    parts['upper'], parts['fore'] = take(arms[0]), take(arms[1])
    parts['shoe'] = take(rest[0])
    out = os.path.join(HERE, name); os.makedirs(out, exist_ok=True)
    spec = {}
    for k, c in parts.items():
        Image.fromarray(c['img']).save(os.path.join(out, k + '.png'), optimize=True)
        m, H, W = c['m'], c['m'].shape[0], c['m'].shape[1]
        if k == 'head':   # face circle: widest skin row gives centre x and radius; bottom of skin gives centre y
            sk = skin_mask(c['img']); lab2, n2 = ndimage.label(sk); big = lab2 == (np.argmax(ndimage.sum(sk, lab2, range(1, n2 + 1))) + 1)
            ys = np.where(big.any(1))[0]; rows = [(big[y].sum(), y) for y in ys]; _, yw = max(rows); x0, x1 = row_span(big, yw)
            R = (x1 - x0) / 2; spec[k] = dict(cx=round((x0 + x1) / 2, 1), cy=round(float(ys.max() - R), 1), R=round(R, 1))
        elif k == 'torso':
            a0, b0 = row_span(m, int(H * .9)); spec[k] = dict(cx=round((a0 + b0) / 2, 1), w=int(np.median([np.ptp(row_span(m, int(H * f))) for f in (.5, .6, .7)])))
        elif k in ('upper', 'fore'):
            cx, w = tube_metrics(m); top = np.where(m.any(1))[0].min(); bot = np.where(m.any(1))[0].max()
            spec[k] = dict(cx=round(cx, 1), w=round(w, 1), y0=int(top + .2 * w), y1=int(bot - (.08 if k == 'upper' else .04) * H))
        elif k == 'leg':
            cx, w = tube_metrics(m); spec[k] = dict(cx=round(cx, 1), w=round(w, 1), y0=0, y1=H)
        elif k in ('hand', 'fist'):   # palm circle: the thumb sticks out to one side, use the rows away from it
            ys = np.where(m.any(1))[0]; R = (ys.max() - ys.min()) / 2; cy = (ys.max() + ys.min()) / 2
            spans = [row_span(m, int(cy + d * R)) for d in (-.6, .6)]; cxs = [(a0 + b0) / 2 for a0, b0 in spans if a0 is not None]
            cx = float(np.mean(cxs)); thumb_right = (W - 1 - cx) > cx
            spec[k] = dict(cx=round(cx, 1), cy=round(cy, 1), R=round(R, 1), thumb=1 if thumb_right else -1)
        elif k == 'shoe':
            a0, b0 = row_span(m, int(H * .8)); spec[k] = dict(cx=round((a0 + b0) / 2, 1), w=int(b0 - a0))
        rgb = c['img'][m][:, :3]
        print(f'{k:6s} {W}x{H} skin={c["skin"]:.2f}', spec[k])
    # elbow cap colour: the top of the forearm (sleeve for jackets, skin for t-shirts), away from the outline
    f = parts['fore']['img']; Hf, Wf = f.shape[:2]; core = f[int(Hf * .12):int(Hf * .3), int(Wf * .3):int(Wf * .7)]; mm = core[..., 3] > 250
    med = np.median(core[mm][:, :3], axis=0).astype(int); spec['sleeve'] = '#%02x%02x%02x' % tuple(med)
    json.dump(spec, open(os.path.join(out, 'spec.json'), 'w'), indent=1)
    write_specs()

if __name__ == '__main__':
    if sys.argv[1] == '--specs': write_specs()
    else: main(sys.argv[1], sys.argv[2])
